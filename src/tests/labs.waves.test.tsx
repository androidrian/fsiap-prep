import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it } from 'vitest'
import { MemoryRouter } from 'react-router-dom'
import { unpolarizedThroughPolarizers } from '../domain/exercises/calculators'
import { LIGHT_YEAR, antennaLengths, blockRay, brewsterAngle, brewsterGeometry, claddingIndexForAcceptance, criticalAngle, fiber, fieldAmplitudes, isotropicSource, lightInMedium, planeWave, radioService, snellAngle, spectrumBand, visibleColour } from '../labs/waves/physics'
import { SimulatorsPage } from '../pages/SimulatorsPage'

afterEach(cleanup)

const renderLab = (query: string) => render(<MemoryRouter initialEntries={[`/simulators?${query}`]}><SimulatorsPage /></MemoryRouter>)
const slide = (name: RegExp, value: number) => fireEvent.change(screen.getByRole('slider', { name }), { target: { value: String(value) } })
const expectClean = (container: HTMLElement) => expect(container.textContent).not.toMatch(/NaN|Infinity/)

describe('wave and optics physics (sheet 4)', () => {
  it('spreads the power of an isotropic source over a sphere (ex. 16, 4 and 6)', () => {
    const lamp = isotropicSource(50, 3)
    expect(lamp.intensity).toBeCloseTo(0.442, 3)
    expect(lamp.electric).toBeCloseTo(18.26, 1)
    expect(lamp.magnetic).toBeCloseTo(6.09e-8, 10)
    expect(lamp.intensityAtDouble).toBeCloseTo(lamp.intensity / 4, 12)
    // Ex. 4: a resposta da ficha (2,45×10⁻² V/m) corresponde a um emissor no solo, que irradia para uma semiesfera.
    expect(isotropicSource(5e4, 1e5, 0.5).electric).toBeCloseTo(2.45e-2, 4)
    expect(isotropicSource(5e4, 1e5).electric).toBeCloseTo(1.73e-2, 4)
    // Ex. 6: a ficha indica 1,2×10⁻³ V/m, que é o valor eficaz; a amplitude é 1,76×10⁻³ V/m.
    const star = isotropicSource(2.2e3 * 3.9e26, 431 * LIGHT_YEAR)
    expect(star.electric).toBeCloseTo(1.76e-3, 5)
    expect(star.electricRms).toBeCloseTo(1.24e-3, 5)
    expect(star.magnetic).toBeCloseTo(5.86e-12, 13)
  })

  it('relates frequency, wavelength, ω, k and the field amplitudes (ex. 1 and 7)', () => {
    const wave = planeWave(1e8, 30)
    expect(wave.wavelength).toBeCloseTo(3, 10)
    expect(wave.omega).toBeCloseTo(2 * Math.PI * 1e8, 0)
    expect(wave.waveNumber).toBeCloseTo(2 * Math.PI / 3, 10)
    expect(wave.magneticAmplitude).toBeCloseTo(1e-7, 12)
    const fields = fieldAmplitudes(20)
    expect(fields.electric).toBeCloseTo(122.8, 1)
    expect(fields.magnetic).toBeCloseTo(4.09e-7, 9)
    expect(planeWave(1e6, fields.electric).intensity).toBeCloseTo(20, 8)
    expect(planeWave(1e6, 1).waveNumber).toBeCloseTo(2 * Math.PI / 3 * 1e-2, 10)
  })

  it('locates frequencies in the spectrum and sizes antennas (ex. 2, 3 and 5)', () => {
    expect(antennaLengths(520e3).wavelength).toBeCloseTo(577, 0)
    expect(antennaLengths(1610e3).wavelength).toBeCloseTo(186, 0)
    expect(antennaLengths(88e6).wavelength).toBeCloseTo(3.41, 2)
    expect(antennaLengths(108e6).wavelength).toBeCloseTo(2.78, 2)
    expect(antennaLengths(1e6)).toMatchObject({ wavelength: 300, half: 150, quarter: 75 })
    expect(antennaLengths(900e6).wavelength).toBeCloseTo(0.333, 3)
    expect(radioService(1e6)).toBe('AM')
    expect(radioService(1e8)).toBe('FM')
    expect(radioService(9e8)).toBeNull()
    expect(spectrumBand(1e6).id).toBe('radio')
    expect(spectrumBand(9e8).id).toBe('microwave')
    expect(spectrumBand(1e14 / (2 * Math.PI)).id).toBe('infrared')
    expect(spectrumBand(430e12).id).toBe('visible')
    expect(spectrumBand(1e15).id).toBe('ultraviolet')
    expect(spectrumBand(1e25).id).toBe('gamma')
    expect(antennaLengths(430e12).wavelength * 1e9).toBeCloseTo(698, 0)
    expect(visibleColour(antennaLengths(430e12).wavelength)?.label).toBe('vermelho')
    expect(antennaLengths(760e12).wavelength * 1e9).toBeCloseTo(395, 0)
    expect(visibleColour(antennaLengths(760e12).wavelength)?.label).toBe('violeta')
    expect(visibleColour(1e-6)).toBeNull()
  })

  it('finds the Brewster condition (ex. 9)', () => {
    expect(brewsterAngle(1, 1.5)).toBeCloseTo(56.31, 2)
    const geometry = brewsterGeometry(brewsterAngle(1, 1.5), 1, 1.5)
    expect(geometry.refracted).toBeCloseTo(33.69, 2)
    expect(geometry.sum).toBeCloseTo(90, 8)
    expect(geometry.between).toBeCloseTo(90, 8)
    expect(geometry.reflectance.parallel).toBeCloseTo(0, 10)
    expect(geometry.reflectance.perpendicular).toBeGreaterThan(0.1)
    expect(brewsterGeometry(80, 1.5, 1).refracted).toBeNull()
    expect(brewsterGeometry(80, 1.5, 1).reflectance).toEqual({ perpendicular: 1, parallel: 1 })
  })

  it('applies Snell and the critical angle (ex. 14)', () => {
    expect(snellAngle(30, 1, 1.5)).toBeCloseTo(19.47, 2)
    expect(snellAngle(60, 1.34, 1)).toBeNull()
    expect(criticalAngle(1, 1.5)).toBeNull()
    // Com n = 1,34 exato dá 48,3°; a ficha (48,6°) usa o quociente 633/474 arredondado de outra forma.
    expect(criticalAngle(1.34, 1)).toBeCloseTo(48.27, 2)
    const water = lightInMedium(633e-9, 1.34)
    expect(water.wavelength * 1e9).toBeCloseTo(472.4, 1)
    expect(water.frequency).toBeCloseTo(4.74e14, -12)
    expect(water.speed).toBeCloseTo(2.24e8, -6)
  })

  it('computes the acceptance cone and the reflections of a fibre (ex. 11, 12, 15 and 17)', () => {
    expect(fiber(1.58, 1.53, 25e-6, 1, 0).acceptanceAngle).toBeCloseTo(23.2, 1)
    expect(fiber(1.486, 1.486 * 0.99, 25e-6, 1, 0).acceptanceAngle).toBeCloseTo(12.1, 1)
    const limit = fiber(1.475, 1.46, 25e-6, 1000, 0).acceptanceAngle
    const result = fiber(1.475, 1.46, 25e-6, 1000, limit)
    expect(result.criticalAngle).toBeCloseTo(81.8, 1)
    expect(result.acceptanceAngle).toBeCloseTo(12.1, 1)
    expect(result.wallAngle).toBeCloseTo(81.8, 1)
    expect(result.guided).toBe(true)
    expect(result.reflections / 1e6).toBeCloseTo(2.87, 2)
    expect(result.bounceSpacing * 1e6).toBeCloseTo(348, 0)
    const leaking = fiber(1.475, 1.46, 25e-6, 1000, 30)
    expect(leaking.guided).toBe(false)
    expect(leaking.leakAngle).not.toBeNull()
    const axial = fiber(1.475, 1.46, 25e-6, 1000, 0)
    expect(axial.reflections).toBe(0)
    expect(Number.isFinite(axial.bounceSpacing)).toBe(false)
    expect(fiber(1.4, 1.5, 25e-6, 1, 10)).toMatchObject({ criticalAngle: null, numericalAperture: 0, guided: false })
    // Ex. 15: os 32° são a abertura total do cone (semi-ângulo de 16°).
    expect(claddingIndexForAcceptance(1.542, 16)).toBeCloseTo(1.517, 3)
  })

  it('follows a ray from the top of a block to its side wall (ex. 10 and 18)', () => {
    const glass = blockRay(45, 1.54, 1, 0.5)
    expect(glass.minIndex).toBeCloseTo(1.22, 2)
    expect(glass.totalReflection).toBe(true)
    expect(glass.transmitted).toBeNull()
    expect(blockRay(45, 1.2, 1, 0.5).totalReflection).toBe(false)
    const plastic = blockRay(45, 1.54, 1.41, 0.5)
    expect(plastic.refracted).toBeCloseTo(27.3, 1)
    expect(plastic.wallIncidence).toBeCloseTo(62.7, 1)
    expect(plastic.totalReflection).toBe(false)
    expect(plastic.transmitted).toBeCloseTo(76, 0)
    expect(plastic.pathLength).toBeCloseTo(1.089, 3)
    expect(plastic.travelTime).toBeCloseTo(5.59e-9, 11)
    // A ficha pede o tempo dentro do plástico até à base (ida até à parede e reflexão): 1,1×10⁻⁸ s.
    expect(2 * plastic.travelTime).toBeCloseTo(1.12e-8, 10)
  })

  it('reproduces the three polarizers of ex. 8 (relative angles 60° and 30°)', () => {
    expect(unpolarizedThroughPolarizers(1, [90, 30, 0]).at(-1)).toBeCloseTo(0.094, 3)
  })
})

describe('wave and optics laboratory scenarios', () => {
  it('draws an isotropic source with the lamp of ex. 16', () => {
    const { container } = renderLab('family=em_waves&scenario=source&P=50&r=3')
    expect(screen.getByRole('button', { name: 'Fonte isotrópica' })).toHaveClass('active')
    expect(screen.getByText('0,442 W/m²')).toBeInTheDocument()
    expect(container.textContent).toContain('18,3 V/m')
    expect(container.textContent).toContain('6,09×10⁻⁸ T')
    const marker = container.querySelector('.lab-waves-bar-marker:not(.ghost)')!
    const before = marker.getAttribute('d')
    slide(/Expoente de r/, 5)
    expect(marker.getAttribute('d')).not.toBe(before)
    fireEvent.click(screen.getByRole('button', { name: 'Rádio 50 kW' }))
    expect(container.textContent).toContain('0,0245 V/m')
    fireEvent.click(screen.getByRole('button', { name: 'Estrela Polar' }))
    expect(container.textContent).toContain('1,76×10⁻³ V/m')
    expect(container.textContent).toContain('1,24×10⁻³ V/m')
    const field = screen.getByRole('textbox', { name: 'Potência emitida P' })
    fireEvent.change(field, { target: { value: '0' } })
    fireEvent.blur(field)
    expectClean(container)
  })

  it('locates a frequency in the spectrum and sizes the antennas of ex. 3', () => {
    const { container } = renderLab('family=em_waves&scenario=spectrum&f=1e6')
    expect(screen.getByRole('button', { name: 'Espetro e antenas' })).toHaveClass('active')
    expect(screen.getByText('300 m')).toBeInTheDocument()
    expect(screen.getByText('75 m')).toBeInTheDocument()
    expect(screen.getByText('rádio (AM)')).toBeInTheDocument()
    expect(container.querySelector('.lab-waves-band.radio')).toHaveClass('active')
    const marker = container.querySelector('.lab-waves-spectrum-marker')!
    const before = marker.getAttribute('d')
    fireEvent.click(screen.getByRole('button', { name: '900 MHz' }))
    expect(marker.getAttribute('d')).not.toBe(before)
    expect(screen.getByText('0,333 m')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '430 THz' }))
    expect(screen.getByText('698 nm')).toBeInTheDocument()
    expect(container.textContent).toContain('visível · vermelho')
    expect(container.querySelector('.lab-waves-zoom')).toHaveClass('active')
    fireEvent.click(screen.getByRole('button', { name: '760 THz' }))
    expect(screen.getByText('395 nm')).toBeInTheDocument()
    expect(container.textContent).toContain('violeta')
    slide(/Expoente de f/, 22)
    expect(container.querySelector('.lab-waves-band.gamma')).toHaveClass('active')
    slide(/Expoente de f/, 3)
    expectClean(container)
  })

  it('shows the fully polarised reflection at the Brewster angle of ex. 9', () => {
    const { container } = renderLab('family=em_waves&scenario=brewster&n1=1&n2=1.5')
    expect(screen.getByRole('button', { name: 'Ângulo de Brewster' })).toHaveClass('active')
    expect(screen.getByText('56,3°')).toBeInTheDocument()
    expect(container.textContent).toContain('33,7°')
    expect(container.querySelector('.lab-waves-right-angle')).toBeInTheDocument()
    expect(container.querySelectorAll('.lab-waves-reflected-marks .lab-waves-pol-arrow')).toHaveLength(0)
    expect(container.querySelectorAll('.lab-waves-reflected-marks .lab-waves-pol-dot').length).toBeGreaterThan(0)
    const reflected = container.querySelector('.lab-waves-ray.reflected')!
    const before = reflected.getAttribute('d')
    slide(/Ângulo de incidência/, 20)
    expect(reflected.getAttribute('d')).not.toBe(before)
    expect(container.querySelector('.lab-waves-right-angle')).not.toBeInTheDocument()
    expect(container.querySelectorAll('.lab-waves-reflected-marks .lab-waves-pol-arrow').length).toBeGreaterThan(0)
    fireEvent.click(screen.getByRole('button', { name: 'Ir para θ_B' }))
    expect(container.querySelector('.lab-waves-right-angle')).toBeInTheDocument()
    slide(/Índice n₁/, 2.5)
    slide(/Ângulo de incidência/, 89)
    expect(container.textContent).toContain('reflexão total')
    slide(/Ângulo de incidência/, 0)
    expectClean(container)
  })

  it('guides the critical ray of the fibre of ex. 17 and leaks beyond the acceptance cone', () => {
    const { container } = renderLab('family=optics&scenario=fiber&nn=1.475&nb=1.46&a=25&L=1000')
    expect(screen.getByRole('button', { name: 'Fibra ótica' })).toHaveClass('active')
    expect(screen.getByText('12,1°')).toBeInTheDocument()
    expect(container.textContent).toContain('81,8°')
    expect(container.textContent).toContain('2,87×10⁶')
    const zigzag = container.querySelector('.lab-waves-zigzag')!
    expect(zigzag).toHaveClass('guided')
    expect(container.querySelectorAll('.lab-waves-ray.leak')).toHaveLength(0)
    const firstSegment = zigzag.querySelector('path')!
    const before = firstSegment.getAttribute('d')
    slide(/Ângulo de entrada/, 30)
    expect(firstSegment.getAttribute('d')).not.toBe(before)
    expect(zigzag).toHaveClass('leaking')
    expect(container.querySelectorAll('.lab-waves-ray.leak').length).toBeGreaterThan(0)
    fireEvent.click(screen.getByRole('button', { name: 'Ir para φmax' }))
    expect(zigzag).toHaveClass('guided')
    slide(/Ângulo de entrada/, 0)
    expect(container.textContent).toContain('sem reflexões')
    slide(/Índice da bainha/, 1.8)
    slide(/Ângulo de entrada/, 89)
    expectClean(container)
  })

  it('answers the other fibre exercises (ex. 11 and the inverse problem of ex. 15)', () => {
    const first = renderLab('family=optics&scenario=fiber&nn=1.58&nb=1.53')
    expect(screen.getByText('23,2°')).toBeInTheDocument()
    first.unmount()
    const { container } = renderLab('family=optics&scenario=fiber&nn=1.542&nb=1.517')
    expect(screen.getByText('1,517')).toBeInTheDocument()
    expect(container.textContent).toContain('1,98×10⁸ m/s')
    expect(container.textContent).toContain('32,0°')
  })

  it('follows the ray of ex. 18 through the block and finds the minimum index of ex. 10', () => {
    const { container } = renderLab('family=optics&scenario=block&theta1=45&n=1.54&nout=1.41&L=50')
    expect(screen.getByRole('button', { name: 'Bloco com parede lateral' })).toHaveClass('active')
    expect(screen.getByText('1,12×10⁻⁸ s')).toBeInTheDocument()
    expect(screen.getByText('5,59×10⁻⁹ s')).toBeInTheDocument()
    expect(container.textContent).toContain('θt = 76,0°')
    expect(container.querySelector('.lab-waves-ray.transmitted')).toBeInTheDocument()
    const refracted = container.querySelector('.lab-waves-ray.refracted')!
    const before = refracted.getAttribute('d')
    slide(/Ângulo de incidência/, 70)
    expect(refracted.getAttribute('d')).not.toBe(before)
    slide(/Ângulo de incidência/, 45)
    const scaleBar = container.querySelectorAll('.lab-waves-dimension')[1]
    const scaleBefore = scaleBar.getAttribute('d')
    expect(container.textContent).toContain('50 cm')
    slide(/Distância L/, 120)
    expect(scaleBar.getAttribute('d')).not.toBe(scaleBefore)
    expect(container.textContent).toContain('1 m')
    slide(/Índice do meio exterior/, 1)
    expect(screen.getByText('1,22')).toBeInTheDocument()
    expect(container.querySelector('.lab-waves-ray.transmitted')).not.toBeInTheDocument()
    expect(container.textContent).toContain('reflexão total na parede')
    slide(/Ângulo de incidência/, 5)
    slide(/Índice do bloco/, 2.5)
    expectClean(container)
    slide(/Ângulo de incidência/, 85)
    slide(/Índice do bloco/, 1)
    expectClean(container)
  })

  it('draws E and B in phase and writes the wave equations of ex. 1 and 7', () => {
    const { container } = renderLab('family=em_waves&scenario=wave&f=1e8&E0=30')
    expect(screen.getByRole('button', { name: 'Onda EM' })).toHaveClass('active')
    expect(screen.getByText('3 m')).toBeInTheDocument()
    expect(container.querySelector('.lab-waves-equations')!.textContent).toContain('30 cos(6,28×10⁸ t − 2,09 x) V/m')
    expect(container.querySelector('.lab-waves-equations')!.textContent).toContain('1,00×10⁻⁷ cos(')
    expect(container.querySelector('.lab-waves-e-curve')).toBeInTheDocument()
    expect(container.querySelector('.lab-waves-b-curve')).toBeInTheDocument()
    const curve = container.querySelector('polyline.lab-waves-e-curve')!
    const before = curve.getAttribute('points')
    slide(/Amplitude E₀ \(cursor\)/, 400)
    expect(curve.getAttribute('points')).not.toBe(before)
    const stretched = curve.getAttribute('points')
    slide(/Expoente de f/, 6)
    expect(curve.getAttribute('points')).not.toBe(stretched)
    expect(screen.getByText('300 m')).toBeInTheDocument()
    const intensity = screen.getByRole('textbox', { name: '…ou a intensidade média I' })
    fireEvent.change(intensity, { target: { value: '20' } })
    fireEvent.blur(intensity)
    expect(screen.getAllByText('123 V/m').length).toBeGreaterThanOrEqual(1)
    expect(container.textContent).toContain('4,09×10⁻⁷ T')
    expect(container.textContent).toContain('6,28×10⁶ rad/s')
    expect(container.textContent).toContain('0,0209 m⁻¹')
    expect(screen.getByRole('button', { name: 'Animar' })).toBeInTheDocument()
    expectClean(container)
  })

  it('accepts the three polarizer axes of ex. 8', () => {
    const { container } = renderLab('family=em_waves&scenario=three&a1=90&a2=30&a3=0')
    expect(screen.getByRole('button', { name: '3 polarizadores' })).toHaveClass('active')
    expect(screen.getByRole('slider', { name: /Eixo de P₁/ })).toHaveValue('90')
    expect(screen.getByRole('slider', { name: /Eixo de P₂/ })).toHaveValue('30')
    expect(screen.getByRole('slider', { name: /Eixo de P₃/ })).toHaveValue('0')
    expect(container.textContent).toContain('I3 = 0,094 I₀')
    const axis = () => container.querySelectorAll('.polarizer-disc i')[1].getAttribute('style')
    const before = axis()
    slide(/Eixo de P₂/, 60)
    expect(axis()).not.toBe(before)
    expectClean(container)
  })

  it('keeps the default three polarizers of the quick question (0°, 45°, 90°)', () => {
    const { container } = renderLab('family=em_waves&scenario=three')
    expect(container.textContent).toContain('I3 = 0,125 I₀')
  })

  it('accepts angle and indices in the Snell and critical-angle scenarios (ex. 14)', () => {
    const snell = renderLab('family=optics&scenario=snell&angle=30&n1=1&n2=1.5')
    expect(screen.getByRole('button', { name: 'Lei de Snell' })).toHaveClass('active')
    expect(screen.getByText('19,5°')).toBeInTheDocument()
    const refracted = snell.container.querySelector('.lab-waves-ray.refracted')!
    const before = refracted.getAttribute('d')
    slide(/Índice n₂/, 2.5)
    expect(refracted.getAttribute('d')).not.toBe(before)
    expectClean(snell.container)
    snell.unmount()

    const { container } = renderLab('family=optics&scenario=critical&angle=40&n1=1.34&n2=1')
    expect(screen.getByRole('button', { name: 'Ângulo crítico' })).toHaveClass('active')
    expect(screen.getByText('48,3°')).toBeInTheDocument()
    expect(screen.getByText('472 nm')).toBeInTheDocument()
    expect(container.querySelector('.lab-waves-ray.refracted')).toBeInTheDocument()
    slide(/Ângulo medido à normal/, 60)
    expect(container.querySelector('.lab-waves-ray.refracted')).not.toBeInTheDocument()
    expect(container.textContent).toContain('reflexão total interna')
    slide(/Índice n₂/, 2.5)
    expect(container.textContent).toContain('não existe')
    expectClean(container)
  })
})
